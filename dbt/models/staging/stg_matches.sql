SELECT
    SAFE_CAST(JSON_VALUE(match_json, '$.match_id') AS INT64) AS match_id,
    SAFE_CAST(JSON_VALUE(match_json, '$.match_week') AS INT64) AS match_week,
    PARSE_DATE('%Y-%m-%d', JSON_VALUE(match_json, '$.match_date')) AS match_date,
    PARSE_TIME('%H:%M:%E*S', JSON_VALUE(match_json, '$.kick_off')) AS kick_off,
    JSON_VALUE(match_json, '$.match_status') AS match_status,
    JSON_VALUE(match_json, '$.match_status_360') AS match_status_360,
    SAFE_CAST(JSON_VALUE(match_json, '$.competition.competition_id') AS INT64) AS competition_id,
    JSON_VALUE(match_json, '$.competition.competition_name') AS competition_name,
    JSON_VALUE(match_json, '$.competition.country_name') AS competition_country,
    SAFE_CAST(JSON_VALUE(match_json, '$.season.season_id') AS INT64) AS season_id,
    JSON_VALUE(match_json, '$.season.season_name') AS season_name,
    SAFE_CAST(JSON_VALUE(match_json, '$.competition_stage.id') AS INT64) AS competition_stage_id,
    JSON_VALUE(match_json, '$.competition_stage.name') AS competition_stage_name,
    SAFE_CAST(JSON_VALUE(match_json, '$.home_team.home_team_id') AS INT64) AS home_team_id,
    JSON_VALUE(match_json, '$.home_team.home_team_name') AS home_team_name,
    JSON_VALUE(match_json, '$.home_team.home_team_gender') AS home_team_gender,
    JSON_VALUE(match_json, '$.home_team.country.name') AS home_team_country,
    SAFE_CAST(JSON_VALUE(match_json, '$.away_team.away_team_id') AS INT64) AS away_team_id,
    JSON_VALUE(match_json, '$.away_team.away_team_name') AS away_team_name,
    JSON_VALUE(match_json, '$.away_team.away_team_gender') AS away_team_gender,
    JSON_VALUE(match_json, '$.away_team.country.name') AS away_team_country,
    SAFE_CAST(JSON_VALUE(match_json, '$.home_score') AS INT64) AS home_score,
    SAFE_CAST(JSON_VALUE(match_json, '$.away_score') AS INT64) AS away_score,
    SAFE_CAST(JSON_VALUE(match_json, '$.referee.id') AS INT64) AS referee_id,
    JSON_VALUE(match_json, '$.referee.name') AS referee_name,
    JSON_VALUE(match_json, '$.referee.country.name') AS referee_country,
    SAFE_CAST(JSON_VALUE(match_json, '$.stadium.id') AS INT64) AS stadium_id,
    JSON_VALUE(match_json, '$.stadium.name') AS stadium_name,
    JSON_VALUE(match_json, '$.stadium.country.name') AS stadium_country,
    JSON_VALUE(match_json, '$.metadata.data_version') AS data_version,
    JSON_VALUE(match_json, '$.metadata.shot_fidelity_version') AS shot_fidelity_version,
    JSON_VALUE(match_json, '$.metadata.xy_fidelity_version') AS xy_fidelity_version,
    SAFE_CAST(JSON_VALUE(match_json, '$.last_updated') AS TIMESTAMP) AS last_updated,
    SAFE_CAST(JSON_VALUE(match_json, '$.last_updated_360') AS TIMESTAMP) AS last_updated_360

FROM {{ source('statsbomb_data', 'raw_matches') }}